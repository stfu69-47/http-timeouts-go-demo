// Random sampling or a global concurrent counter must not change which IDs are slow.
func TestFixtureSelectsExactlyDeclaredRequestIDs(t *testing.T) {
	srv := startFixture(FixtureConfig{SlowEvery: 50, SlowStage: "headers", SlowDelay: time.Nanosecond})
	defer srv.Close()
	c, tr := testClient()
	defer tr.CloseIdleConnections()
	for _, id := range []int{0, 1, 49, 50, 99, 100} {
		r := measure(context.Background(), c, srv.URL, "fixture", id, 0)
		if r.failed() || r.Status != 200 || r.FixtureSlow != (id > 0 && id%50 == 0) || r.Bytes != 64 {
			t.Fatalf("fixture id=%d: %+v", id, r)
		}
	}
}

// DNS timing must be generated by a real resolver exchange, never by a Dial sleep.
func TestLocalDNSFixtureProducesResolverTrace(t *testing.T) {
	dns, err := startDNSFixture(time.Millisecond)
	if err != nil {
		t.Fatal(err)
	}
	defer dns.Close()
	ctx, cancel := context.WithTimeout(context.Background(), time.Second)
	defer cancel()
	rec := newRecorder(time.Now())
	ctx = withRecorder(ctx, rec)
	ips, err := dns.Resolver().LookupIPAddr(ctx, "fixture.test")
	if err != nil || len(ips) != 1 || ips[0].String() != "127.0.0.1" {
		t.Fatalf("lookup=%v err=%v", ips, err)
	}
	events, _ := rec.snapshot()
	ivs := deriveIntervals(events)
	count := 0
	for _, iv := range ivs {
		if iv.Phase == "dns" {
			count++
		}
	}
	if count != 1 {
		t.Fatalf("expected actual DNS callbacks: %+v", events)
	}
}

// TLS reuse must eliminate handshakes in subsequent requests while retaining h1.
func TestHTTPSFixtureUsesTrustedCertificateAndReuses(t *testing.T) {
	srv := startFixture(FixtureConfig{TLS: true, TLSDelay: time.Millisecond})
	defer srv.Close()
	roots := x509.NewCertPool()
	if srv.Certificate() == nil {
		t.Fatal("fixture is not HTTPS")
	}
	roots.AddCert(srv.Certificate())
	c, tr := newClient(ClientConfig{Concurrency: 1, MaxConns: 1, Timeout: time.Second, RootCAs: roots})
	defer tr.CloseIdleConnections()
	var rows []RequestRecord
	for i := 1; i <= 2; i++ {
		rows = append(rows, measure(context.Background(), c, srv.URL, "tls", i, 0))
	}
	s := summarize("tls", rows)
	if s.IOErrors != 0 || s.NewConnections != 1 || s.ReusedConnections != 1 || s.Phases["tls"].N != 1 || rows[0].Protocol != "HTTP/1.1" {
		t.Fatalf("TLS result: %+v", s)
	}
}
